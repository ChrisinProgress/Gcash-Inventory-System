import { execFileSync, execSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const web = new URL('public/', root);
const fonts = new URL('fonts/', web);
const scripts = new URL('js/', web);
const esbuildVersion = '0.25.12';

function replaceRequired(source, search, replacement) {
  if (!source.includes(search)) throw new Error(`Offline build could not find ${search}`);
  return source.replace(search, () => replacement);
}

async function inlineFonts(stylesheet) {
  const urls = [...stylesheet.matchAll(/url\((\.\/files\/[\w.-]+\.woff2)\)/g)];
  if (!urls.length) throw new Error('The Poppins stylesheet has no WOFF2 references.');
  const embedded = await Promise.all(urls.map(async ([url, path]) => {
    const bytes = await readFile(new URL(path, fonts));
    return [url, `url(data:font/woff2;base64,${bytes.toString('base64')})`];
  }));
  return embedded.reduce((css, [url, data]) => css.replaceAll(url, data), stylesheet);
}

function bundle(source) {
  const args = ['--bundle', '--format=iife', '--platform=browser', '--target=es2022', '--charset=utf8', '--sourcefile=app.js'];
  const options = { cwd: fileURLToPath(scripts), input: source, encoding: 'utf8', maxBuffer: 4 * 1024 * 1024 };
  const executable = process.env.GCASH_ESBUILD_PATH;
  if (executable) return execFileSync(executable, args, options);
  return execSync(`npx --yes esbuild@${esbuildVersion} ${args.join(' ')}`, options);
}

const [template, fontCss, mainCss, operationsCss, app, license] = await Promise.all([
  readFile(new URL('index.html', web), 'utf8'),
  readFile(new URL('poppins.css', fonts), 'utf8'),
  readFile(new URL('styles.css', web), 'utf8'),
  readFile(new URL('operations.css', web), 'utf8'),
  readFile(new URL('app.js', scripts), 'utf8'),
  readFile(new URL('OFL', fonts), 'utf8'),
]);

// Keep the Firebase SDK and project configuration out of the portable file.
const localApp = replaceRequired(app, "import * as firebase from './firebase.js';", 'const firebase = { isConfigured: false, isEmulator: false };');
const launch = `<script>
if (location.protocol === 'http:' || location.protocol === 'https:') {
  const hosted = new URL('./public/index.html', location.href);
  hosted.search = location.search;
  hosted.hash = location.hash;
  location.replace(hosted);
} else if (location.protocol === 'file:') {
${bundle(localApp)}}
</script>`;
const replacements = [
  ['<!doctype html>', '<!doctype html>\n<!-- Generated by scripts/build-offline.mjs from public/. Edit the source files there. -->'],
  ['<html lang="en-PH">', '<html lang="en-PH" data-mode="local">'],
  ['<link rel="stylesheet" href="./fonts/poppins.css">', `<style id="poppins-fonts">\n${await inlineFonts(fontCss)}\n</style>\n<!-- Poppins license\n${license.trim()}\n-->`],
  ['<link rel="stylesheet" href="./styles.css">', `<style>\n${mainCss}\n</style>`],
  ['<link rel="stylesheet" href="./operations.css">', `<style>\n${operationsCss}\n</style>`],
  ['<script type="module" src="./js/app.js"></script>', launch],
];
const output = replacements.reduce((html, [search, replacement]) => replaceRequired(html, search, replacement), template);
await writeFile(new URL('index.html', root), output.replaceAll('\r\n', '\n'), 'utf8');
console.log('Built index.html');
